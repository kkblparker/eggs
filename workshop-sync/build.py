#!/usr/bin/env python3
"""Builds the NightHowl Barotrauma and Starbound eggs.

Starts from the official community eggs in upstream/ (pelican-eggs/games-steamcmd)
and adds:
  - the Steam Workshop tab (feature `steam_workshop` + the hidden WORKSHOP_*
    variables the panel's dev.kkblparker.steamworkshop extension reads)
  - nighthowl-workshop.sh, written into the server by the install
    script and run before the game on every start
  - Barotrauma only: name / password / max players / public listing variables
    and the panel's assigned port (stock egg always used 27015)

Run:  python build.py      -> writes ../barotrauma/egg-barotrauma.json and
                              ../starbound/egg-starbound.json (PLCN_v1, like the
                              other eggs in this repo).
Editing the sync script? Re-run this, re-import the egg, then reinstall
existing servers (reinstall keeps saves; it re-writes the script).
"""

import json
from datetime import datetime, timezone
from pathlib import Path

HERE = Path(__file__).parent
SCRIPT = (HERE / "nighthowl-workshop.sh").read_text(encoding="utf-8").replace("\r\n", "\n")
MARKER = "NIGHTHOWL_WORKSHOP_EOF"
assert MARKER not in SCRIPT

WRITE_SCRIPT = f"""
## NightHowl: Workshop sync script (runs before the server on every start)
cat > /mnt/server/nighthowl-workshop.sh <<'{MARKER}'
{SCRIPT.rstrip()}
{MARKER}
chmod +x /mnt/server/nighthowl-workshop.sh
"""


def var(name, env, default, rules, description, viewable=True, editable=True):
    return {
        "name": name,
        "description": description,
        "env_variable": env,
        "default_value": default,
        "user_viewable": viewable,
        "user_editable": editable,
        "rules": rules,
        "sort": None,
        "field_type": "text",
    }


def workshop_vars(appid, game):
    return [
        var(
            "Workshop Mods",
            "WORKSHOP_MODS",
            "",
            "nullable|string|max:8192",
            f"Managed by the Steam Workshop tab - use that instead of editing this. "
            f"Mods are downloaded and enabled every time the server starts.",
        ),
        var("[System] Steam Workshop App ID", "WORKSHOP_APPID", appid, "required|string|in:" + appid,
            f"Steam app the {game} Workshop items belong to.", False, False),
        var("[System] Workshop Mods Variable", "WORKSHOP_MODS_VARIABLE", "WORKSHOP_MODS",
            "required|string|in:WORKSHOP_MODS", "Tells the Steam Workshop tab which variable holds the mod list.",
            False, False),
    ]


def load(name):
    return json.loads((HERE / "upstream" / name).read_text(encoding="utf-8"))


def to_plcn(egg):
    """Upstream is PTDL_v2; this repo's eggs are PLCN_v1 (rules as a list,
    numbered sort, no field_type)."""
    egg["meta"] = {"version": "PLCN_v1", "update_url": None}
    for i, v in enumerate(egg["variables"], start=1):
        rules = v["rules"]
        if isinstance(rules, str):
            rules = [r for r in rules.split("|") if r]
        egg["variables"][i - 1] = {
            "sort": i,
            "name": v["name"],
            "description": v["description"],
            "env_variable": v["env_variable"],
            "default_value": v["default_value"],
            "user_viewable": v["user_viewable"],
            "user_editable": v["user_editable"],
            "rules": rules,
        }


def finish(egg, uuid, out):
    egg["uuid"] = uuid
    egg["exported_at"] = datetime.now(timezone.utc).replace(microsecond=0).isoformat()
    egg["_comment"] = "NightHowl build of the pelican-eggs community egg - generated by workshop-sync/build.py, edit that instead"
    features = egg.get("features") or []
    if "steam_workshop" not in features:
        features.append("steam_workshop")
    egg["features"] = features
    to_plcn(egg)
    out = HERE.parent / out
    out.parent.mkdir(exist_ok=True)
    out.write_text(json.dumps(egg, indent=4, ensure_ascii=False) + "\n", encoding="utf-8")
    print("wrote", out)


# --- Barotrauma ---------------------------------------------------------------
egg = load("egg-barotrauma.json")
egg["name"] = "Barotrauma"
egg["description"] = (
    "Barotrauma is a 2D co-op survival horror submarine simulator. NightHowl build: "
    "Steam Workshop tab, server name / password / player settings, and the panel's assigned ports. "
    "Uses two ports: the game port and game port + 1 (Steam query), both UDP."
)
egg["startup"] = (
    "[ -f ./nighthowl-workshop.sh ] && bash ./nighthowl-workshop.sh barotrauma; "
    "./DedicatedServer -batchmode -port ${SERVER_PORT} -queryport $((${SERVER_PORT}+1)) "
    "-name \"${SERVER_NAME}\" -maxplayers ${MAX_PLAYERS} "
    "-public $( [ \"${PUBLIC}\" = \"1\" ] && echo true || echo false ) "
    "$( [ -n \"${SERVER_PASSWORD}\" ] || printf %s -nopassword ) ${SERVER_PASSWORD:+-password \"${SERVER_PASSWORD}\"} "
    "2>&1 | sed -u -r \"s/\\x1B\\[([0-9]{1,3}(;[0-9]{1,2})?)?[mGK]//g\""
)
install = egg["scripts"]["installation"]["script"].replace("\r\n", "\n")
install = install.replace("## add below your custom commands if needed\n", "## add below your custom commands if needed\n" + WRITE_SCRIPT)
assert MARKER in install
egg["scripts"]["installation"]["script"] = install
egg["variables"] += [
    var("Server Name", "SERVER_NAME", "A NightHowl Barotrauma Server", "required|string|max:60",
        "Name shown in the server browser."),
    var("Server Password", "SERVER_PASSWORD", "", "nullable|string|max:64",
        "Leave empty for no password."),
    var("Max Players", "MAX_PLAYERS", "16", "required|integer|between:1,32", "Maximum number of players."),
    var("Public", "PUBLIC", "1", "required|boolean", "Show the server in the public server browser."),
] + workshop_vars("602960", "Barotrauma")
finish(egg, "740f7f4f-ce3d-4a06-a6c4-e2737488988d", "barotrauma/egg-barotrauma.json")

# --- Starbound ------------------------------------------------------------------
egg = load("egg-starbound.json")
egg["name"] = "Starbound"
egg["description"] = (
    "Starbound dedicated server. NightHowl build: Steam Workshop tab (mods download on start). "
    "Needs a Steam account that owns Starbound to install/update the game (admin-only variables); "
    "Workshop mods download anonymously. Players must have the same mods subscribed to join."
)
egg["startup"] = "[ -f ./nighthowl-workshop.sh ] && bash ./nighthowl-workshop.sh starbound; ./starbound_server"
install = egg["scripts"]["installation"]["script"].replace("\r\n", "\n")
# The stock "WORKSHOP" block only linked items downloaded by hand; the sync script replaces it.
start = install.index("## use Worksop content")
install = install[:start].rstrip() + "\n" + WRITE_SCRIPT
egg["scripts"]["installation"]["script"] = install
egg["variables"] = [v for v in egg["variables"] if v["env_variable"] != "WORKSHOP"] + workshop_vars("211820", "Starbound")
finish(egg, "bd58ca59-f9d8-472a-be18-74a1df211024", "starbound/egg-starbound.json")
